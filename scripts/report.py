"""Make Pareto plots and results/RESULTS.md from the CSVs written by bench.py."""
from __future__ import annotations

import json
import math
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

VARIANTS = {
    "synth_test_16k": "Synthetic TTS, 16 kHz",
    "synth_test_8k": "Synthetic TTS, 8 kHz telephony",
    "edacc_test_16k": "EdAcc real conversation, 16 kHz",
    "edacc_test_8k": "EdAcc real conversation, 8 kHz telephony",
}
CURVES = [
    ("silence_silero", "Silence threshold (Silero VAD)", "#7f7f7f", "o"),
    ("silence_webrtc", "Silence threshold (WebRTC VAD)", "#bcbcbc", "s"),
    ("smart_turn_v3", "Smart Turn v3 (threshold x fallback)", "#d62728", "^"),
    ("hazard_prosody", "Hazard: prosody only", "#9467bd", "."),
    ("hazard_text_asr", "Hazard: text only (ASR)", "#2ca02c", "."),
    ("hazard_fusion_asr", "Hazard: prosody + text (ASR)", "#1f77b4", "D"),
    ("hazard_fusion_oracle", "Hazard: prosody + text (oracle text)", "#17becf", "x"),
]


def frontier(df: pd.DataFrame, lat: str) -> pd.DataFrame:
    """Lower-left Pareto frontier of (latency, cut-off rate)."""
    d = df[np.isfinite(df[lat])].sort_values([lat, "cutoff_rate"])
    keep, best = [], np.inf
    for i, r in d.iterrows():
        if r.cutoff_rate < best - 1e-12:
            keep.append(i)
            best = r.cutoff_rate
    return d.loc[keep]


def fmt_ms(v):
    return "inf" if (isinstance(v, float) and math.isinf(v)) else ("-" if pd.isna(v) else f"{v:.0f}")


def fmt_pct(v):
    return "-" if pd.isna(v) else f"{100 * v:.1f}%"


def pareto_plot(curves: pd.DataFrame, var: str, out: str, lat="latency_p50_ms"):
    fig, ax = plt.subplots(figsize=(7.2, 4.8), dpi=150)
    d = curves[curves.variant == var]
    for system, label, color, marker in CURVES:
        c = frontier(d[d.system == system], lat)
        if c.empty:
            continue
        ax.plot(c[lat], 100 * c.cutoff_rate, marker=marker, ms=3.5, lw=1.4, color=color, label=label,
                drawstyle="steps-post" if system.startswith(("smart", "hazard")) else "default")
    for T in (300, 500, 800, 1200):
        r = d[(d.system == "silence_silero") & (d.param == str(T))]
        if len(r) and np.isfinite(r[lat].iloc[0]):
            ax.annotate(f"{T} ms", (r[lat].iloc[0], 100 * r.cutoff_rate.iloc[0]), textcoords="offset points",
                        xytext=(4, 4), fontsize=7, color="#555")
    which = "median (p50)" if lat.endswith("p50_ms") else "p95"
    ax.set_xlabel(f"End-of-turn latency, {which} (ms)")
    ax.set_ylabel("Premature cut-off rate (% of turns)")
    ax.set_title(f"{VARIANTS[var]}: Pareto frontier per system", fontsize=10)
    ax.set_xlim(0, 3300)
    ax.set_ylim(bottom=0)
    ax.grid(alpha=0.25)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(fontsize=7, frameon=False)
    fig.tight_layout()
    fig.savefig(out)
    plt.close(fig)


def frontier_cutoff(curves, var, system, p50, p95):
    c = curves[(curves.variant == var) & (curves.system == system) &
               (curves.latency_p50_ms <= p50) & (curves.latency_p95_ms <= p95)]
    return c.cutoff_rate.min() if len(c) else math.nan


def main():
    curves = pd.read_csv("results/curves.csv")
    heads = pd.read_csv("results/headline.csv")
    slices = pd.read_csv("results/slices.csv")
    ops = json.load(open("results/operating_points.json"))
    timing = json.load(open("results/compute_timing.json"))
    os.makedirs("results/plots", exist_ok=True)
    for var in VARIANTS:
        pareto_plot(curves, var, f"results/plots/pareto_{var}.png")
        pareto_plot(curves, var, f"results/plots/pareto_p95_{var}.png", lat="latency_p95_ms")

    L = ["# Results", "", "Generated by `scripts/report.py` from `results/*.csv`. All numbers come from",
         "runs of this repository on an Apple M1 Max (CPU only).", ""]
    L += ["## Headline table", "",
          "Cut-off = premature end-of-turn (system fired before the user finished). Latency is measured",
          "from the true turn end, over turns that were not cut off. Late/miss = no fire within 2 s.", ""]
    for var, title in VARIANTS.items():
        h = heads[heads.variant == var]
        if h.empty:
            continue
        L += [f"### {title} (n = {int(h.n.iloc[0])} turns)", "",
              "| system | config | cut-off | p50 latency (ms) | p95 latency (ms) | late/miss |",
              "|---|---|---:|---:|---:|---:|"]
        for _, r in h.iterrows():
            L.append(f"| {r.system} | {r.config} | {fmt_pct(r.cutoff_rate)} | {fmt_ms(r.latency_p50_ms)} | "
                     f"{fmt_ms(r.latency_p95_ms)} | {fmt_pct(r.late_or_miss_rate)} |")
        L.append("")
    L += ["## Frontier lookup (descriptive)", "",
          "Lowest cut-off rate each system reaches anywhere on its *test* grid while keeping both p50 and",
          "p95 latency at or below those of the Silero silence baseline. This picks settings on test data, so",
          "it describes the curves (an upper bound); the train-selected operating points above are the",
          "unbiased comparison.", "",
          "| test set | baseline | baseline cut-off | Smart Turn v3 | hazard fusion (ASR) | hazard fusion (oracle) |",
          "|---|---|---:|---:|---:|---:|"]
    for var, title in VARIANTS.items():
        for T in (300, 500, 800, 1200):
            b = curves[(curves.variant == var) & (curves.system == "silence_silero") & (curves.param == str(T))]
            if b.empty:
                continue
            p50, p95 = b.latency_p50_ms.iloc[0], b.latency_p95_ms.iloc[0]
            L.append(f"| {title} | Silero {T} ms (p50 {fmt_ms(p50)} / p95 {fmt_ms(p95)} ms) | "
                     f"{fmt_pct(b.cutoff_rate.iloc[0])} | "
                     f"{fmt_pct(frontier_cutoff(curves, var, 'smart_turn_v3', p50, p95))} | "
                     f"{fmt_pct(frontier_cutoff(curves, var, 'hazard_fusion_asr', p50, p95))} | "
                     f"{fmt_pct(frontier_cutoff(curves, var, 'hazard_fusion_oracle', p50, p95))} |")
    L.append("")
    key = ["silence_silero|300 ms", "silence_silero|500 ms", "silence_silero|800 ms", "silence_silero|1200 ms",
           "smart_turn_v3|p>0.5, fallback 3000 ms (defaults)"]
    key += sorted({f"{r.system}|{r.config}" for r in heads.itertuples()
                   if r.system in ("hazard_fusion_asr", "smart_turn_v3") and "matched" in r.config})
    slices["key"] = slices.system + "|" + slices.config
    for dim in ["max_pause_ms", "inserted_pause_ms", "filler", "filler_type", "split_kind", "accent_group"]:
        s = slices[(slices.slice == dim) & (slices.key.isin(key))]
        if s.empty:
            continue
        L += [f"## Cut-off rate by {dim}", ""]
        for var, title in VARIANTS.items():
            sv = s[s.variant == var]
            if sv.empty:
                continue
            vals = sorted(sv.value.unique(), key=lambda v: (len(v) > 6 and not v[0].isdigit(), int(v.split()[0]) if v.split()[0].isdigit() else 0, v))
            counts = {v: int(sv[sv.value == v].n.iloc[0]) for v in vals}
            L += [f"**{title}**", "", "| system | " + " | ".join(f"{v} (n={counts[v]})" for v in vals) + " |",
                  "|---|" + "---:|" * len(vals)]
            for k in key:
                row = sv[sv.key == k].set_index("value")
                if row.empty:
                    continue
                L.append(f"| {k.replace('|', ' ')} | " + " | ".join(
                    fmt_pct(row.cutoff_rate.get(v, np.nan)) + " / " + fmt_ms(row.latency_p50_ms.get(v, np.nan))
                    for v in vals) + " |")
            L += ["", "(cells: cut-off rate / median latency in ms)", ""]
    L += ["## Operating points (chosen on out-of-fold training predictions)", "", "```",
          json.dumps({d: {k: {T: (x["param"], x.get("train", {}).get("cutoff_rate")) for T, x in v.items()}
                          for k, v in o["chosen"].items()} for d, o in ops.items()}, indent=1), "```", "",
          "## Per-decision compute time (CPU, 7 parallel extraction workers, M1 Max, 16 kHz sets)", "", "```",
          json.dumps(timing, indent=1), "```", ""]
    open("results/RESULTS.md", "w").write("\n".join(L))
    print("wrote results/RESULTS.md and results/plots/")


if __name__ == "__main__":
    main()
